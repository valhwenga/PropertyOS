-- ---------------------------------------------------------------------------
-- 0062  Changing what a lease bills every month
-- ---------------------------------------------------------------------------
--
-- `charge_schedules` was built effective-dated from the first migration. Its
-- own comment says it: "a rent increase closes the old row and opens a new one;
-- the historical amount stays readable." Nothing has ever done that. A rent
-- schedule is written once when a lease is activated and never changes again,
-- and there is no screen to add a recurring parking bay, a levy or a refuse
-- charge at all.
--
-- The consequence is not cosmetic. A lease agreement generated by this product
-- says the rent increases by the escalation in its own terms on each
-- anniversary, `leases.escalation_percent` holds that figure, and the billing
-- run keeps raising the original amount for the whole term. The product bills
-- a number that contradicts the agreement it printed.
--
-- Two columns, so a change leaves a trail that reads in the right order:
-- which row replaced which, and the reason a person gave for it.

alter table charge_schedules
  add column if not exists supersedes_schedule_id uuid,
  add column if not exists change_reason text
    check (change_reason is null or length(btrim(change_reason)) between 3 and 300);

alter table charge_schedules
  drop constraint if exists charge_schedules_supersedes_fk,
  add constraint charge_schedules_supersedes_fk
    foreign key (organisation_id, supersedes_schedule_id)
    references charge_schedules (organisation_id, id) on delete restrict;

comment on column charge_schedules.supersedes_schedule_id is
  'The row this one replaced. A rent increase closes the old period and opens '
  'a new row from the effective date, so the amount billed in any past month '
  'stays readable exactly as it was billed.';

comment on column charge_schedules.change_reason is
  'Why the amount changed, in a person''s words. Shown on the lease and in the '
  'audit trail; a rent increase with no reason recorded is one nobody can '
  'account for later.';

-- Reading one lease's schedules, current and historical, in date order. The
-- lease page does this on every visit.
create index if not exists charge_schedules_lease_period_idx
  on charge_schedules (organisation_id, lease_id, lower(effective_period));

