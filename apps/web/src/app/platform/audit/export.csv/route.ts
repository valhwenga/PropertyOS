import { NextResponse } from 'next/server';
import { platformAuditTrail } from '@propertyos/domain';
import { getViewer, readPrivilegedAs } from '@/lib/auth';

/**
 * The same view, as a file.
 *
 * A review that has to be shown to somebody — an auditor, a customer asking
 * what Spike did in their account, a colleague — travels as a file, and the
 * file has to say what it covers. So the filters are written into the head of
 * it: a row torn out of context is how an audit extract becomes misleading.
 *
 * It reads the query string the screen writes and calls the SAME function, so
 * a download from a filtered page cannot quietly contain more than the page
 * showed. The report exports learned that the hard way and the comment there
 * says so; this starts from it.
 *
 * `toCsv` in the reports module is not reused on purpose: it writes a currency
 * and a period into every file because a financial report has both, and an
 * audit extract has neither. Borrowing it would have put "Currency: ZAR" at
 * the top of a list of operator actions.
 */
export async function GET(request: Request) {
  const viewer = await getViewer();
  if (!viewer) return new NextResponse('Unauthorised', { status: 401 });

  const url = new URL(request.url);
  const kindParam = url.searchParams.get('kind');
  const kind: 'all' | 'platform' | 'support' =
    kindParam === 'platform' || kindParam === 'support' ? kindParam : 'all';
  const operator = url.searchParams.get('operator');
  const customer = url.searchParams.get('customer');
  const action = url.searchParams.get('action');
  const from = url.searchParams.get('from');
  const to = url.searchParams.get('to');

  const filter = {
    kind,
    ...(operator ? { operatorUserId: operator } : {}),
    ...(customer ? { organisationId: customer } : {}),
    ...(action ? { action } : {}),
    ...(from ? { from } : {}),
    ...(to ? { to } : {}),
    // Higher than the screen's: the file is where somebody goes when the page
    // said it was showing only the most recent few hundred.
    limit: 1000,
  };

  let trail;
  try {
    trail = await readPrivilegedAs(viewer, (tx) =>
      platformAuditTrail(tx, viewer.authUserId, filter));
  } catch {
    // The permission is resolved in SQL by the function above. A refusal here
    // is a refusal, not a server fault, and it says nothing about what exists.
    return new NextResponse('Not found', { status: 404 });
  }

  const escape = (v: unknown) => `"${String(v ?? '').replace(/"/g, '""')}"`;
  const lines = [
    ['Spike PropertyOS — what Spike has done'].map(escape).join(','),
    ['Generated at', new Date().toISOString()].map(escape).join(','),
    ['Generated by', viewer.fullName].map(escape).join(','),
    ['Showing', kind === 'all'
      ? 'account actions and changes inside customer records'
      : kind === 'support'
        ? 'changes inside customer records, under authorised sessions'
        : 'actions on customer accounts'].map(escape).join(','),
    ['Operator', operator ? 'one operator only' : 'everybody'].map(escape).join(','),
    ['Customer', customer ? 'one customer only' : 'all customers'].map(escape).join(','),
    ['Action', action ?? 'any'].map(escape).join(','),
    ['From', from ?? 'the beginning'].map(escape).join(','),
    ['To', to ?? 'now'].map(escape).join(','),
    ['Rows in this file', String(trail.rows.length)].map(escape).join(','),
    ['Rows matching the filters', String(trail.total)].map(escape).join(','),
    // Stated in the file itself, because somebody will read the file long
    // after the page that produced it is gone.
    ['Note',
      'Every row is an action by Spike on a customer account or inside their records, '
      + 'or the customer\'s own decision about such a session — approving or ending it. '
      + 'A customer\'s ordinary work does not appear.']
      .map(escape).join(','),
    '',
    [
      'When', 'Operator', 'Action', 'Customer', 'Why', 'Resource type', 'Resource id',
      'Inside their records', 'Session allowed', 'Approved by',
    ].map(escape).join(','),
  ];

  for (const row of trail.rows) {
    lines.push([
      row.at,
      row.actorName ?? '',
      row.action,
      row.organisationName ?? 'Spike itself',
      row.reason ?? '',
      row.resourceType,
      row.resourceId ?? '',
      row.supportSessionId ? 'yes' : 'no',
      row.supportSessionId
        ? (row.supportScopes.length === 0 ? 'read-only' : row.supportScopes.join(' '))
        : '',
      row.approvedByName ?? '',
    ].map(escape).join(','));
  }

  const stamp = new Date().toISOString().slice(0, 10);
  return new NextResponse(`${lines.join('\n')}\n`, {
    headers: {
      'content-type': 'text/csv; charset=utf-8',
      'content-disposition': `attachment; filename="spike-conduct-${stamp}.csv"`,
      // An audit extract is private data about named people. Nothing caches it.
      'cache-control': 'no-store',
    },
  });
}
